#include <iostream>

// Повертає вказівник на ПЕРШИЙ найбільший елемент масиву a довжиною n.
const int* max_ptr(const int* a, int n) {
    // Спочатку вважаємо найбільшим перший елемент: best вказує на a[0].
    const int* best = a;

    // Починаємо з i = 1, бо a[0] уже взято як кандидата.
    for (int i = 1; i < n; ++i) {
        // *best - значення, на яке зараз вказує best.
        // Строге ">" (не ">="): рівний елемент не замінює попередній,
        // тому лишається перший максимум.
        if (a[i] > *best) {
            best = a + i;   // a + i - вказівник на елемент з індексом i
        }
    }
    return best;            // повертаємо адресу, а не саме число
}
int main() {
    int a[5] = {3, 9, 2, 9, 5};
    const int* p = max_ptr(a, 5);

    // *p - значення найбільшого елемента,
    // p - a - різниця вказівників = кількість елементів між a і p, тобто індекс.
    std::cout << *p << ' ' << (p - a) << '\n';
}